document.addEventListener('DOMContentLoaded', () => {
  const grid = document.getElementById('productGrid');
  const filters = document.getElementById('productFilters');
  const viewAll = document.getElementById('viewAllProducts');
  const results = document.getElementById('productResults');
  const posterViewer = document.querySelector('.business-poster-slides');
  const posterIndicators = document.querySelectorAll('[data-poster-indicator]');
  if (!grid) return;

  let currentFilter = 'all';
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');

  const genderLabel = (gender) => ({ him: 'For Him', her: 'For Her', unisex: 'Unisex' }[gender] || gender);

  function renderProducts() {
    const items = window.products.filter((product) => currentFilter === 'all' || product.gender === currentFilter);

    grid.innerHTML = items.map((product) => `
      <article class="product-card" data-product-card="${product.id}">
        <div class="product-image">
          <img src="${product.image}" alt="${product.shortName} KENSCENT perfume" loading="lazy">
          <span class="product-badge">${genderLabel(product.gender)}</span>
        </div>
        <div class="product-content">
          <div class="product-title-row">
            <h4>${product.shortName}</h4>
            <span class="product-price">${product.price}</span>
          </div>
          <p>${product.category}</p>
          <button class="product-details-btn" type="button" data-product-id="${product.id}">View Details</button>
        </div>
      </article>
    `).join('');
    if (results) {
      results.textContent = currentFilter === 'all'
        ? `Showing all ${items.length} scents.`
        : `Showing ${items.length} scents ${genderLabel(currentFilter).toLowerCase()}.`;
    }
  }

  function syncActiveFilter() {
    filters?.querySelectorAll('[data-product-filter]').forEach((item) => {
      const isActive = item.dataset.productFilter === currentFilter;
      item.classList.toggle('active', isActive);
      item.setAttribute('aria-pressed', String(isActive));
    });
  }

  function changeFilter(nextFilter) {
    if (nextFilter === currentFilter) return;
    currentFilter = nextFilter;
    syncActiveFilter();
    renderProducts();
    if (!reducedMotion.matches) {
      grid.classList.remove('is-entering');
      void grid.offsetWidth;
      grid.classList.add('is-entering');
      window.setTimeout(() => grid.classList.remove('is-entering'), 180);
    }
  }

  function populateProductModal(product) {
    const modal = document.getElementById('productModal');
    const content = document.getElementById('productModalContent');
    const title = document.getElementById('productModalTitle');
    if (!modal || !content) return;
    if (title) title.textContent = `${product.name} details`;
    const message = encodeURIComponent(`Hi! I am interested in KENSCENT ${product.shortName}. Is it available?`);
    content.innerHTML = `
      <div class="product-modal-layout">
        <div class="product-modal-media"><img src="${product.poster}" alt="${product.shortName} product poster"></div>
        <div class="product-modal-copy">
          <p class="eyebrow gold">${genderLabel(product.gender)} • KENSCENT</p>
          <h2>${product.name}</h2>
          <div class="product-modal-price">${product.price}</div>
          <p class="product-modal-description">${product.description}</p>
          <div class="note-list">
            <div><strong>Top Notes</strong><span>${product.topNotes}</span></div>
            <div><strong>Heart Notes</strong><span>${product.heartNotes}</span></div>
            <div><strong>Base Notes</strong><span>${product.baseNotes}</span></div>
          </div>
          <div class="modal-actions">
            <a class="btn btn-gold" href="https://m.me/kenzo.ozamiz?text=${message}" target="_blank" rel="noopener noreferrer">Message on Facebook</a>
            <a class="btn btn-secondary" href="mailto:pioquentokennith@gmail.com?subject=KENSCENT%20Order%20Inquiry&body=${message}">Contact to Order</a>
          </div>
        </div>
      </div>`;
    return modal;
  }

  function openProduct(product, trigger) {
    const modal = document.getElementById('productModal');
    const dialog = modal?.querySelector('.modal-dialog');
    const card = trigger?.closest('[data-product-card]');
    const canMorph = document.startViewTransition && !reducedMotion.matches && modal && dialog && card;
    if (!canMorph) {
      populateProductModal(product);
      window.openPortfolioModal?.(modal, trigger);
      return;
    }

    card.style.viewTransitionName = 'product-morph';
    const transition = document.startViewTransition(() => {
      card.style.viewTransitionName = '';
      dialog.style.viewTransitionName = 'product-morph';
      populateProductModal(product);
      window.openPortfolioModal?.(modal, trigger);
    });
    transition.finished.finally(() => {
      card.style.viewTransitionName = '';
      dialog.style.viewTransitionName = '';
    });
  }

  filters?.addEventListener('click', (event) => {
    const button = event.target.closest('[data-product-filter]');
    if (!button) return;
    changeFilter(button.dataset.productFilter);
  });

  viewAll?.addEventListener('click', () => {
    changeFilter('all');
    grid.scrollIntoView({ behavior: reducedMotion.matches ? 'auto' : 'smooth', block: 'start' });
  });

  function selectPoster(selectedPoster) {
    document.querySelectorAll('[data-business-poster-image]').forEach((image) => {
      image.classList.toggle('active', image.dataset.businessPosterImage === selectedPoster);
    });
    posterIndicators.forEach((indicator) => indicator.classList.toggle('active', indicator.dataset.posterIndicator === selectedPoster));
    posterViewer?.setAttribute('aria-label', `Show ${selectedPoster === 'front' ? 'back' : 'front'} of KENSCENT poster`);
  }

  function flipPoster() {
    const showingFront = document.querySelector('[data-business-poster-image="front"]')?.classList.contains('active');
    selectPoster(showingFront ? 'back' : 'front');
  }

  posterViewer?.addEventListener('click', flipPoster);
  posterViewer?.addEventListener('keydown', (event) => {
    if (!['Enter', ' ', 'ArrowLeft', 'ArrowRight'].includes(event.key)) return;
    event.preventDefault();
    if (event.key === 'ArrowLeft') selectPoster('front');
    else if (event.key === 'ArrowRight') selectPoster('back');
    else flipPoster();
  });

  grid.addEventListener('click', (event) => {
    const button = event.target.closest('[data-product-id]');
    if (!button) return;
    const product = window.products.find((item) => item.id === Number(button.dataset.productId));
    if (product) openProduct(product, button);
  });

  syncActiveFilter();
  renderProducts();
});
